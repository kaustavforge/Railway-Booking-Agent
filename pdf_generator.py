"""
pdf_generator.py — IRCTC-style Electronic Reservation Slip (ERS)
==================================================================
Drop-in replacement for the previous version. Same two function names/
signatures (fetch_booking_for_pdf, generate_irctc_ticket_pdf) so your
FastAPI endpoint (main.py's /api/download-ticket/{pnr}) needs no changes.

WHAT CHANGED VS. THE PREVIOUS VERSION, AND WHY:
  - fetch_booking_for_pdf now ALSO reads trains.csv/schedules.csv/
    stations.csv to fill in fields the DB alone can't provide:
      * Departure time (at source) / Arrival time (at destination) —
        pulled from schedules.csv for this train_number.
      * Distance (km) — estimated from station lat/lon (haversine
        straight-line distance). This is an ESTIMATE, not real IRCTC
        route-km — flagged in the PDF as approximate.
  - generate_irctc_ticket_pdf is rewritten to match the reference
    layout: circular logo placeholders, a "Booked From -> Boarding At
    -> To" row with an arrow graphic, a fare breakdown (ticket fare +
    convenience fee + insurance = total), a QR code encoding the PNR,
    a fabricated-but-realistic-looking GST/invoice block, and an
    acronym legend — all built with reportlab (canvas overlay for the
    logos/arrow/QR/watermark, Platypus tables for the data grids).

HONEST LIMITATIONS (please read before treating this as "real"):
  1. SPECIMEN WATERMARK: every ticket generated by this script is
     stamped "SPECIMEN — NOT A VALID TRAVEL DOCUMENT" diagonally across
     the page. This is a demo/portfolio project generating tickets from
     synthetic data, not real IRCTC — the watermark keeps that honest
     and prevents the output from being mistaken for (or misused as) a
     genuine ticket.
  2. NO REAL LOGOS: the "IR" / "IRCTC" roundels are plain stylized text
     in circles, not the actual official emblems — reproducing the real
     government/IRCTC logo artwork isn't something this script does.
  3. SINGLE PASSENGER ONLY: your bookings table stores one
     `passenger_name` + a `num_passengers` count per PNR — it has no
     per-passenger Age/Gender/name-list the way a real multi-passenger
     PNR does. The Age/Gender columns are rendered as "-" placeholders
     for this reason. If you want real multi-passenger tickets (2+
     named passengers, each with their own age/gender/seat), that needs
     a schema change: a separate `passengers` table keyed by
     pnr_number. Ask if you want that built.
  4. GSTIN / Invoice number / SAC code are FABRICATED placeholder
     values in a realistic format — not a real registered GSTIN.
  5. Distance is a straight-line estimate between station coordinates,
     not the actual rail route distance.

Install (adds qrcode + Pillow to your existing requirements):
    pip install reportlab qrcode pillow --break-system-packages

Data files expected next to this script (same folder as railway_code_cloud.py):
    pnr_bookings.db, trains.csv, schedules.csv, stations.csv
"""

